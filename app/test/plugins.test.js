import { describe, expect, it } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { CREATE_LIMIT, createKeeper, folders } from '../keeper.js';
import { choose, dailyPattern, detect, isGenerated, owns, resolvePlugins, scanContext } from '../plugins.js';
import { plan, writeStarter } from '../starter.js';

const NOTE = (title, date, people = []) => `---\ntitle: ${title}\ndate: ${date}T15:00:00-08:00\nparticipants:\n${people.map((p) => `  - ${p}`).join('\n')}\nsource: quorum\n---\n\n# ${title}\n\nNotes.\n`;
const put = (dir, rel, text) => { mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true }); writeFileSync(path.join(dir, rel), text); };
const GEN_INDEX = '<!-- Auto-generated by scripts/wiki-index.py. Do not hand-edit. -->\n# Index\n\n- [[a]] a note\n';

// a vault with its own tooling: an index generator that marks its output, and daily briefs named <date>-brief.md
function toolingVault() {
  const dir = mkdtempSync(path.join(tmpdir(), 'plugins-own-'));
  put(dir, 'index.md', GEN_INDEX);
  put(dir, 'scripts/wiki-index.py', 'print("index")\n');
  for (const d of ['2026-11-01', '2026-11-02', '2026-11-03']) put(dir, `01-daily/${d}-brief.md`, `# ${d}\n`);
  put(dir, '02-people/ada-lovelace.md', '# Ada Lovelace\n');
  put(dir, '08-meetings/2026-11-10-sync.md', NOTE('Sync', '2026-11-10', ['Ada Lovelace']));
  put(dir, '08-meetings/2026-11-11-plan.md', NOTE('Plan', '2026-11-11'));
  return dir;
}
const keeperFor = (dir, settings = { keeper: { on: true } }, over = {}) => createKeeper({ brain: () => ({ root: dir, vault: dir }), settings, ...over });
const rowsFor = (dir, saved) => resolvePlugins(detect(scanContext(dir, dir, folders(dir))), saved);

describe('plugin detection', () => {
  it('reads generated markers from the first lines only', () => {
    expect(isGenerated(GEN_INDEX)).toBe(true);
    expect(isGenerated('# Index\n\nGenerated by build-index.js\n')).toBe(true);
    expect(isGenerated('# Notes\n\nDo not edit this section by hand.\n')).toBe(true);
    expect(isGenerated('# Index\n\nOne line per note.\n')).toBe(false);
    expect(isGenerated(`${'line\n'.repeat(12)}auto-generated\n`)).toBe(false);
  });
  it('finds the daily naming the folder already uses', () => {
    expect(dailyPattern(['2026-11-01-brief.md', '2026-11-02-brief.md', '2026-11-03.md', 'README.md']).template).toBe('{date}-brief.md');
    expect(dailyPattern(['2026-11-01.md', 'notes.md']).template).toBe('{date}.md');
    expect(dailyPattern([]).template).toBe('{date}.md');
  });
  it('defaults jobs with tooling to the vault and names the evidence', () => {
    const dir = toolingVault();
    put(dir, 'MEMORY.md', '# Memory\n');
    put(dir, 'scripts/search-memory.py', '');
    const rows = rowsFor(dir);
    const by = Object.fromEntries(rows.map((r) => [r.id, r]));
    expect(by.index).toMatchObject({ owner: 'vault', isNew: true });
    expect(by.index.evidence.map((e) => e.path)).toEqual(['index.md', 'scripts/wiki-index.py']);
    expect(by.daily).toMatchObject({ owner: 'vault', isNew: true });
    expect(by.daily.evidence[0]).toMatchObject({ path: '01-daily/2026-11-03-brief.md' });
    expect(by.facts.evidence[0]).toMatchObject({ path: 'MEMORY.md', why: 'memory system' });
    expect(by.search).toMatchObject({ owner: 'vault' });
    expect(by.search.evidence.map((e) => e.path)).toEqual(['scripts/search-memory.py']);
    expect(by.links).toMatchObject({ owner: 'quorum', isNew: false, evidence: [] });
  });
  it('a bare vault leaves every job with Quorum and nothing new', () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-bare-'));
    writeStarter(dir, plan({ name: 'Studio', answers: { template: 'founder', role: 'Designer', goals: '', projects: ['Quorum'], people: [], organize: 'areas' } }));
    for (const r of rowsFor(dir)) expect(r).toMatchObject({ owner: 'quorum', isNew: false, evidence: [] });
  });
  it('keeps a choice until the evidence changes, then brings the vault default back as new', () => {
    const dir = toolingVault();
    let saved = choose({}, rowsFor(dir), 'index', 'quorum');
    let index = rowsFor(dir, saved).find((r) => r.id === 'index');
    expect(index).toMatchObject({ owner: 'quorum', overridden: true, isNew: false });
    put(dir, 'scripts/rebuild-index.sh', '');
    index = rowsFor(dir, saved).find((r) => r.id === 'index');
    expect(index).toMatchObject({ owner: 'vault', isNew: true });
    // leaving it with the vault clears the badge
    saved = choose(saved, rowsFor(dir, saved), 'index', 'vault');
    expect(rowsFor(dir, saved).find((r) => r.id === 'index')).toMatchObject({ owner: 'vault', isNew: false });
    expect(owns(rowsFor(dir, saved), 'index')).toBe(false);
  });
});

describe('keeper with plugins', () => {
  it('writes nothing to a vault that owns the index and daily jobs', async () => {
    const dir = toolingVault();
    const dailyBefore = readdirSync(path.join(dir, '01-daily')).sort();
    const k = keeperFor(dir, undefined, { runText: async () => '- Ada leads design', hasModel: () => true, owner: () => 'Rick Bot' });
    put(dir, 'MEMORY.md', '# Memory\n');
    const r = await k.run();
    expect(r).toMatchObject({ filed: 2, held: null });
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe(GEN_INDEX);
    expect(readdirSync(path.join(dir, '01-daily')).sort()).toEqual(dailyBefore);
    expect(existsSync(path.join(dir, 'CLAUDE.md'))).toBe(false);
    // the job Quorum still owns runs as before
    expect(readFileSync(path.join(dir, '02-people', 'ada-lovelace.md'), 'utf8')).toContain('[[2026-11-10-sync]]');
    expect(k.status().plugins.filter((p) => p.isNew).map((p) => p.id)).toEqual(['index', 'daily', 'facts']);
  });
  it('writes daily lines into the vault naming once the job is handed to Quorum', async () => {
    const dir = toolingVault();
    const settings = { keeper: { on: true } };
    const k = keeperFor(dir, settings);
    k.setPlugin('daily', 'quorum');
    expect(settings.plugins.daily).toMatchObject({ owner: 'quorum' });
    await k.run();
    expect(readFileSync(path.join(dir, '01-daily', '2026-11-10-brief.md'), 'utf8')).toContain('- [[2026-11-10-sync]] Sync');
    expect(existsSync(path.join(dir, '01-daily', '2026-11-10.md'))).toBe(false);
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe(GEN_INDEX);
  });
  it('skips a generated file even when Quorum owns the job, and names it', async () => {
    const dir = toolingVault();
    put(dir, '02-people/ada-lovelace.md', '<!-- generated by people-sync -->\n# Ada Lovelace\n');
    const r = await keeperFor(dir).run();
    expect(r.marked).toEqual(['02-people/ada-lovelace.md']);
    expect(readFileSync(path.join(dir, '02-people', 'ada-lovelace.md'), 'utf8')).not.toContain('[[');
  });
  it('holds a run that would create more than the limit of new files until the user allows it', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-many-'));
    mkdirSync(path.join(dir, '01-daily'));
    put(dir, 'index.md', '# Index\n');
    for (let i = 1; i <= CREATE_LIMIT + 2; i++) { const d = `2026-10-${String(i).padStart(2, '0')}`; put(dir, `08-meetings/${d}-m.md`, NOTE(`M${i}`, d)); }
    const k = keeperFor(dir);
    const r = await k.run();
    expect(r.held).toMatchObject({ count: CREATE_LIMIT + 2 });
    expect(r.filed).toBe(0);
    expect(readdirSync(path.join(dir, '01-daily'))).toEqual([]);
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe('# Index\n');
    expect(k.status().held).toMatchObject({ count: CREATE_LIMIT + 2 });
    const go = await k.run({ allowCreate: true });
    expect(go).toMatchObject({ filed: CREATE_LIMIT + 2, held: null });
    expect(readdirSync(path.join(dir, '01-daily'))).toHaveLength(CREATE_LIMIT + 2);
    expect(k.status().held).toBeNull();
  });
});
