import { describe, expect, it } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { CREATE_LIMIT, LEARNED_HEADER, createKeeper, folders, keeperHome } from '../keeper.js';
import { choose, dailyPattern, isGenerated, owns, resolvePlugins } from '../plugins.js';
import { plan, writeStarter } from '../starter.js';

const NOTE = (title, date, people = []) => `---\ntitle: ${title}\ndate: ${date}T15:00:00-08:00\nparticipants:\n${people.map((p) => `  - ${p}`).join('\n')}\nsource: quorum\n---\n\n# ${title}\n\nNotes.\n`;
const put = (dir, rel, text) => { mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true }); writeFileSync(path.join(dir, rel), text); };
const GEN_INDEX = '<!-- Auto-generated by scripts/wiki-index.py. Do not hand-edit. -->\n# Index\n\n- [[a]] a note\n';

// a vault with its own tooling: an index generator that marks its output, and daily briefs named <date>-brief.md
function toolingVault() {
  const dir = mkdtempSync(path.join(tmpdir(), 'plugins-own-'));
  put(dir, 'index.md', GEN_INDEX);
  put(dir, 'scripts/wiki-index.py', 'print("index")\n');
  for (const d of ['2026-11-01', '2026-11-02', '2026-11-03']) put(dir, `01-daily/${d}-brief.md`, `# ${d}\n`);
  put(dir, '02-people/ada-lovelace.md', '# Ada Lovelace\n');
  put(dir, '08-meetings/2026-11-10-sync.md', NOTE('Sync', '2026-11-10', ['Ada Lovelace']));
  put(dir, '08-meetings/2026-11-11-plan.md', NOTE('Plan', '2026-11-11'));
  return dir;
}
// files an earlier run made, recorded in the keeper's state the way a run records them
const madeBy = (dir, made) => put(keeperHome(`${dir}.data`, dir), 'keeper.json', JSON.stringify({ done: {}, made }));
const keeperFor = (dir, settings = { keeper: { on: true } }, over = {}) => createKeeper({ brain: () => ({ root: dir, vault: dir }), dataDir: `${dir}.data`, settings, ...over });

describe('generated notices and daily naming', () => {
  it('reads generated markers from the first lines only', () => {
    expect(isGenerated(GEN_INDEX)).toBe(true);
    expect(isGenerated('# Index\n\nGenerated by build-index.js\n')).toBe(true);
    expect(isGenerated('# Notes\n\nDo not edit this file by hand.\n')).toBe(true);
    expect(isGenerated('---\ngenerated_by: daily-brief\n---\n# 2026-11-10\n')).toBe(true);
    expect(isGenerated('%% auto-generated %%\n# Brief\n')).toBe(true);
    expect(isGenerated('<!-- generated -->\n# Index\n')).toBe(true);
    expect(isGenerated('# Index\n<!-- Generated by wiki-index.py -->\n')).toBe(true);
    expect(isGenerated('<!-- Generated ideas below, edit freely -->\n# Ideas\n')).toBe(false);
    expect(isGenerated('%% generated: false %%\n# Brief\n')).toBe(false);
    expect(isGenerated('<!-- generated: wiki-index.py -->\n# Index\n')).toBe(true);
    expect(isGenerated('---\ngenerated: false\n---\n# Note\n')).toBe(false);
    expect(isGenerated('# Vault Index\n\n> Auto-generated by wiki-index.py. Last updated: 2026-11-13 04:00.\n')).toBe(true);
    expect(isGenerated('<!-- regenerated lines below are mine -->\n# Index\n')).toBe(false);
    // ordinary prose that only mentions editing or generating is not a notice
    expect(isGenerated('# Setup\n\nDo not edit .env directly; use the template.\n')).toBe(false);
    expect(isGenerated('# Notes\n\nDo not edit this section by hand.\n')).toBe(false);
    expect(isGenerated('# Ideas\n\nIdeas generated by the team last week.\nThe report was auto-generated, then fixed.\n')).toBe(false);
    expect(isGenerated('# Index\n\nOne line per note.\n')).toBe(false);
    expect(isGenerated(`${'line\n'.repeat(12)}auto-generated\n`)).toBe(false);
  });
  it('finds the daily naming the folder already uses', () => {
    expect(dailyPattern(['2026-11-01-brief.md', '2026-11-02-brief.md', '2026-11-03.md', 'README.md']).template).toBe('{date}-brief.md');
    expect(dailyPattern(['2026-11-01.md', 'notes.md']).template).toBe('{date}.md');
    expect(dailyPattern([]).template).toBe('{date}.md');
  });
});

describe('plugin owners', () => {
  it('gives every job to Quorum when nothing is saved in a folder Quorum built', () => {
    expect(resolvePlugins().map((r) => [r.id, r.owner])).toEqual([['index', 'quorum'], ['daily', 'quorum'], ['links', 'quorum'], ['facts', 'quorum']]);
    expect(resolvePlugins({}).every((r) => owns([r], r.id))).toBe(true);
  });
  it("leaves every job with the person's own setup when nothing is saved in a folder they connected", () => {
    expect(resolvePlugins({}, { built: false }).every((r) => r.owner === 'vault')).toBe(true);
    expect(owns(resolvePlugins({ daily: { owner: 'quorum' } }, { built: false }), 'daily')).toBe(true);
  });
  it('keeps a saved vault owner, also one saved with the older evidence key', () => {
    const rows = resolvePlugins({ index: { owner: 'vault', ack: 'index.md:marked as generated' }, daily: { owner: 'quorum', ack: '' }, links: { owner: 'other' } });
    expect(owns(rows, 'index')).toBe(false);
    expect(owns(rows, 'daily')).toBe(true);
    expect(owns(rows, 'links')).toBe(true);
    expect(owns(rows, 'facts')).toBe(true);
  });
  it('saves a pick for a known job only', () => {
    expect(choose({}, 'index', 'vault')).toEqual({ index: { owner: 'vault' } });
    expect(choose({ index: { owner: 'vault' } }, 'index', 'quorum')).toEqual({ index: { owner: 'quorum' } });
    expect(choose({}, 'context', 'vault')).toEqual({});
    expect(choose({}, 'index', 'nobody')).toEqual({});
  });
});

describe('keeper with plugins', () => {
  it('writes nothing for the jobs a saved choice gives to the vault', async () => {
    const dir = toolingVault();
    const dailyBefore = readdirSync(path.join(dir, '01-daily')).sort();
    const plugins = { index: { owner: 'vault', ack: 'x' }, daily: { owner: 'vault', ack: 'x' }, facts: { owner: 'vault', ack: 'x' } };
    const k = keeperFor(dir, { keeper: { on: true }, plugins }, { runText: async () => '- Ada leads design', hasModel: () => true, owner: () => 'Rick Bot' });
    const r = await k.run();
    expect(r).toMatchObject({ filed: 2, held: null });
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe(GEN_INDEX);
    expect(readdirSync(path.join(dir, '01-daily')).sort()).toEqual(dailyBefore);
    expect(existsSync(path.join(dir, 'Quorum'))).toBe(false);
    expect(existsSync(path.join(dir, 'CLAUDE.md'))).toBe(false);
    // the job Quorum still owns leaves the people note the person made as it is, and names it
    expect(readFileSync(path.join(dir, '02-people', 'ada-lovelace.md'), 'utf8')).toBe('# Ada Lovelace\n');
    expect(r.left).toEqual(['02-people/ada-lovelace.md']);
    expect(k.status().plugins.filter((p) => p.owner === 'vault').map((p) => p.id)).toEqual(['index', 'daily', 'facts']);
  });
  it('files meetings in a new Quorum-built vault with nothing saved', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-new-'));
    writeStarter(dir, plan({ name: 'Studio', answers: { template: 'founder', role: 'Designer', goals: '', projects: ['Quorum'], people: [], organize: 'areas' } }));
    const f = folders(dir);
    put(dir, `${f.meetings}/2026-11-10-sync.md`, NOTE('Sync', '2026-11-10'));
    const k = keeperFor(dir);
    expect(k.status().plugins.every((p) => p.owner === 'quorum')).toBe(true);
    const r = await k.run();
    expect(r).toMatchObject({ filed: 1, held: null });
    expect(readFileSync(path.join(dir, f.daily, '2026-11-10.md'), 'utf8')).toContain('[[2026-11-10-sync]]');
  });
  it('leaves files the person made alone with nothing saved', async () => {
    const dir = toolingVault();
    put(dir, 'index.md', '# My index\n');
    const before = readFileSync(path.join(dir, '01-daily', '2026-11-01-brief.md'), 'utf8');
    put(dir, '01-daily/2026-11-10-brief.md', '# 2026-11-10\n');
    await keeperFor(dir).run();
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe('# My index\n');
    expect(readFileSync(path.join(dir, '01-daily', '2026-11-10-brief.md'), 'utf8')).toBe('# 2026-11-10\n');
    expect(readFileSync(path.join(dir, '02-people', 'ada-lovelace.md'), 'utf8')).toBe('# Ada Lovelace\n');
    expect(readFileSync(path.join(dir, '01-daily', '2026-11-01-brief.md'), 'utf8')).toBe(before);
  });
  it('writes daily lines into the vault naming once the job is handed to Quorum', async () => {
    const dir = toolingVault();
    const settings = { keeper: { on: true } };
    const k = keeperFor(dir, settings);
    k.setPlugin('daily', 'quorum');
    expect(settings.plugins.daily).toMatchObject({ owner: 'quorum' });
    await k.run();
    expect(readFileSync(path.join(dir, '01-daily', '2026-11-10-brief.md'), 'utf8')).toContain('- [[2026-11-10-sync]] Sync');
    expect(existsSync(path.join(dir, '01-daily', '2026-11-10.md'))).toBe(false);
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe(GEN_INDEX);
  });
  it('skips a generated file even when Quorum owns the job, and names it', async () => {
    const dir = toolingVault();
    put(dir, '02-people/ada-lovelace.md', '<!-- generated by people-sync -->\n# Ada Lovelace\n');
    const r = await keeperFor(dir).run();
    expect(r.marked).toEqual(['index.md', '02-people/ada-lovelace.md']);
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toBe(GEN_INDEX);
    expect(readFileSync(path.join(dir, '02-people', 'ada-lovelace.md'), 'utf8')).not.toContain('[[');
  });
  it('holds a run that would create more than the limit of new files until the user allows it', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-many-'));
    mkdirSync(path.join(dir, '01-daily'));
    put(dir, 'index.md', '# Index\n');
    madeBy(dir, ['index.md']);
    for (let i = 1; i <= CREATE_LIMIT + 2; i++) { const d = `2026-10-${String(i).padStart(2, '0')}`; put(dir, `08-meetings/${d}-m.md`, NOTE(`M${i}`, d)); }
    const k = keeperFor(dir, { keeper: { on: true } });
    const r = await k.run();
    expect(r.held).toMatchObject({ count: CREATE_LIMIT + 2 });
    expect(r.filed).toBe(0);
    expect(readdirSync(path.join(dir, '01-daily'))).toEqual([]);
    // lines that go into files already there are written while the new files wait
    expect(readFileSync(path.join(dir, 'index.md'), 'utf8')).toContain('[[2026-10-01-m]]');
    expect(k.status().held).toMatchObject({ count: CREATE_LIMIT + 2 });
    const go = await k.run({ allowCreate: true });
    expect(go).toMatchObject({ filed: CREATE_LIMIT + 2, held: null });
    expect(readdirSync(path.join(dir, '01-daily'))).toHaveLength(CREATE_LIMIT + 2);
    expect(k.status().held).toBeNull();
  });

  it('files the notes that need no new file while holding the rest', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-mixed-'));
    put(dir, 'index.md', '# Index\n');
    put(dir, '01-daily/2026-09-01.md', '# 2026-09-01\n');
    put(dir, 'Quorum/learned-facts.md', LEARNED_HEADER);
    madeBy(dir, ['index.md', '01-daily/2026-09-01.md']);
    put(dir, '08-meetings/2026-12-01-x.md', NOTE('X', '2026-09-01'));
    for (let i = 1; i <= CREATE_LIMIT + 1; i++) { const d = `2026-10-${String(i).padStart(2, '0')}`; put(dir, `08-meetings/${d}-m.md`, NOTE(`M${i}`, d)); }
    const calls = [];
    const k = keeperFor(dir, { keeper: { on: true } }, { runText: async (p) => { calls.push(p); return `- fact from ${p.match(/Meeting: (\S+)/)[1]}`; }, hasModel: () => true });
    const r = await k.run();
    expect(r.filed).toBe(1);
    expect(r.held.count).toBe(CREATE_LIMIT + 1);
    expect(readFileSync(path.join(dir, '01-daily', '2026-09-01.md'), 'utf8')).toContain('[[2026-12-01-x]]');
    expect(calls).toHaveLength(CREATE_LIMIT + 2);
    expect(readFileSync(path.join(dir, 'Quorum', 'learned-facts.md'), 'utf8')).toContain('fact from M11 ([[2026-10-11-m]], 2026-10-11)');
    // the held notes are not sent for facts a second time when they are filed
    await k.run({ allowCreate: true });
    expect(calls).toHaveLength(CREATE_LIMIT + 2);
    expect(readdirSync(path.join(dir, '01-daily'))).toHaveLength(CREATE_LIMIT + 2);
  });
  it('runs allowCreate after a pass already in flight', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-queue-'));
    mkdirSync(path.join(dir, '01-daily'));
    for (let i = 1; i <= CREATE_LIMIT + 1; i++) { const d = `2026-10-${String(i).padStart(2, '0')}`; put(dir, `08-meetings/${d}-m.md`, NOTE(`M${i}`, d)); }
    const k = keeperFor(dir);
    const first = k.run();
    const second = k.run({ allowCreate: true });
    expect((await first).held).not.toBeNull();
    expect(await second).toMatchObject({ held: null, filed: CREATE_LIMIT + 1 });
  });
  it('clears a held run when a plugin is turned off', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'plugins-clear-'));
    mkdirSync(path.join(dir, '01-daily'));
    for (let i = 1; i <= CREATE_LIMIT + 1; i++) { const d = `2026-10-${String(i).padStart(2, '0')}`; put(dir, `08-meetings/${d}-m.md`, NOTE(`M${i}`, d)); }
    const k = keeperFor(dir);
    await k.run();
    expect(k.status().held).not.toBeNull();
    expect(k.setPlugin('daily', 'vault').held).toBeNull();
  });
  it('turns facts back on when the facts job is handed back to Quorum', async () => {
    const dir = toolingVault();
    const settings = { keeper: { on: true, facts: true } };
    const k = keeperFor(dir, settings, { runText: async () => '- Ada leads design', hasModel: () => true });
    k.setPlugin('facts', 'vault');
    expect(settings.keeper.facts).toBeUndefined();
    expect(k.status()).toMatchObject({ facts: false });
    k.setPlugin('facts', 'quorum');
    expect(k.status()).toMatchObject({ facts: true });
    await k.run();
    expect(readFileSync(path.join(dir, 'Quorum', 'learned-facts.md'), 'utf8')).toContain('Ada leads design');
  });
});
